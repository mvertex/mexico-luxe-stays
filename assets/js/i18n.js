/* ---------- Engine ---------- */
(function () {
  "use strict";

  /* Each language has its own URLs: English at /page.html, Spanish at
     /es/page.html (generated by scripts/build-es.mjs). The page's language
     comes from its path; the stored preference only steers the toggle. */
  const ES_PREFIX = /^\/es(\/|$)/;
  const PAGE_LANG = ES_PREFIX.test(location.pathname) ? "es" : "en";

  function currentLang() {
    return PAGE_LANG;
  }

  function urlFor(lang) {
    const enPath = location.pathname.replace(ES_PREFIX, "/");
    return (lang === "es" ? "/es" + enPath : enPath) + location.search + location.hash;
  }

  /* i18n strings link pages relative to the site root ("privacy.html");
     pages one folder down (villas/) need "../" in front. */
  const UP = "../".repeat(location.pathname.replace(ES_PREFIX, "/").split("/").length - 2);
  const fixLinks = (html) => (UP ? html.replace(/href="(?![a-z]+:|\/|#|\.\.\/)/g, `href="${UP}`) : html);

  function storePref(lang) {
    try { localStorage.setItem("mlsLang", lang); } catch (e) { /* storage blocked */ }
  }

  function applyLanguage(lang) {
    const dict = MLS_I18N[lang] || MLS_I18N.en;
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key] != null) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (dict[key] != null) el.innerHTML = fixLinks(dict[key]);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria-label");
      if (dict[key] != null) el.setAttribute("aria-label", dict[key]);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      const key = el.getAttribute("data-i18n-alt");
      if (dict[key] != null) el.setAttribute("alt", dict[key]);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (dict[key] != null) el.setAttribute("title", dict[key]);
    });

    document.querySelectorAll("[data-lang-toggle]").forEach((toggle) => {
      toggle.querySelectorAll("[data-lang-option]").forEach((opt) => {
        const isActive = opt.getAttribute("data-lang-option") === lang;
        opt.classList.toggle("is-active", isActive);
        opt.setAttribute("aria-pressed", String(isActive));
      });
    });

    document.dispatchEvent(new CustomEvent("mls:languagechange", { detail: { lang } }));
  }

  function t(key, lang) {
    const dict = MLS_I18N[lang || currentLang()] || MLS_I18N.en;
    return dict[key] != null ? dict[key] : (MLS_I18N.en[key] || key);
  }

  /* This script is deferred, so the static page is already parsed here:
     translate it now and start the hero entrance, instead of waiting for
     DOMContentLoaded — which only fires after villas-data.js, main.js etc.
     have also run, holding the (translated) hero title invisible meanwhile.
     The DOMContentLoaded pass below still runs for main.js-rendered content
     and its mls:languagechange listeners. */
  applyLanguage(currentLang());
  const hero = document.querySelector(".hero");
  if (hero) requestAnimationFrame(() => hero.classList.add("is-ready"));

  document.addEventListener("DOMContentLoaded", () => {
    applyLanguage(currentLang());
    document.querySelectorAll("[data-lang-option]").forEach((btn) => {
      btn.addEventListener("click", () => {
        const lang = btn.getAttribute("data-lang-option");
        storePref(lang);
        if (lang !== PAGE_LANG) location.href = urlFor(lang);
      });
    });
  });

  window.mlsT = t;
  window.mlsCurrentLang = currentLang;
  window.mlsApplyLanguage = applyLanguage;
})();
